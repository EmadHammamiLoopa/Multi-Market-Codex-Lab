# Preserve rolling features exactly; no approximate time bucketing is allowed.
ROLLING_WINDOWS_EXACT_TIMESTAMP_BASED = True
APPROXIMATE_SECOND_BUCKETING_FORBIDDEN = True
FEATURE_WARMUP_SEMANTICS_FROZEN = True
RECENT_BOOK_ASOF_250MS_FROZEN = True
