EVENT_SOURCE_ORDER_WITHIN_TIMESTAMP_GROUP_FROZEN = True
LOCAL_BOOK_BEFORE_SAME_TIMESTAMP_FLOWS_FROZEN = True
FINAL_TIMESTAMP_GROUP_FLUSH_REQUIRED = True
NATURAL_END_OF_SOURCE_SEMANTICS_FROZEN = True

# Preserve exact book semantics. Implementation may use compiled/vector state,
# but visible results must equal R9/R10/R20 exactly.
ABSOLUTE_DEPTH_UPDATE_SEMANTICS_FROZEN = True
CLEAR_SEMANTICS_FROZEN = True
SNAPSHOT_SEMANTICS_FROZEN = True
TRADE_DOES_NOT_MUTATE_L2_FROZEN = True
IGNORED_L2_EVENT_POLICY_FROZEN = True
BBO_VALIDITY_RULE_FROZEN = True
TOP5_DEPTH_SEMANTICS_FROZEN = True
