PYTHON_PER_ROW_LOOP_FORBIDDEN_IN_ACCELERATED_REAL_PATH = True
PYTHON_BOOK_OBJECT_MATERIALIZATION_PER_GROUP_FORBIDDEN = True
PYTHON_FULL_BOOK_SORT_PER_GROUP_FORBIDDEN = True

# Preserve frozen raw-event semantics.
LOCAL_STREAM_SEMANTICS_FROZEN = True
